"""
提示词配置 - 集中管理项目中所有大模型提示词
==========================================

修改本文件即可调整总结效果，无需改动任何脚本。

占位符说明（运行时自动替换，请勿删除或改名）：
  {title}        文档标题
  {text}         文档正文核心片段（跳过封面/目录/页码后截取）
  {doc_count}    参与汇总的文档总数
  {all_content}  全部文档的一句话总结+核心看点
  {date_str}     日期字符串（如 2026090815）

注意：
- 占位符之外的 { } 花括号可以自由使用（仅已知占位符会被替换）
- 每个提示词都带"乱码识别"指令，请勿删除，否则识别困难文档会进入总结清单
"""


def render_prompt(template, **kwargs):
    """将模板中的 {name} 占位符替换为实际值。
    仅替换传入键对应的占位符，提示词中其他花括号保持不变，可放心自由编辑。"""
    for key, value in kwargs.items():
        template = template.replace('{%s}' % key, str(value))
    return template


